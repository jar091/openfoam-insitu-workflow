#!/bin/bash
# Benchmark of the mesioVDB export (single vs distributed Mesio writer, blosc vs none) on
# the cavity3D 8M case (icoFoam, 256 ranks on 2 nodes, exports every 10 steps, 40 steps).
#
# Usage (login node; the work runs inside the Slurm job):
#   bash scripts/tests/bench_mesioVDB_writer.sh <tag> <build> <density> [writer] [compression]
#     build   prod (install/mesio + $FOAM_USER_LIBBIN, legacy writer) | <variant> (e.g. dev:
#             install/mesio-dev + install/openfoam-modules-mesio-dev/lib)
#     density voxels along the cube edge (320 -> 32.8 M voxels, 504 -> 128 M voxels)
#     writer / compression: dev only (distributed|single, blosc|none)
# Case: $CASE (default runs/mesio_dev/c3d8M_256: blockMesh 200^3 + decomposePar scotch 256,
# a copy of runs/cavity3D/8M/system with endTime 0.04). Output VDB_<tag>/, log log.icoFoam.<tag>.
set -euo pipefail
PROJ=/mnt/proj2/eu-25-121/milanjaros/openfoam
CASE=${CASE:-/scratch/project/eu-25-121/milanjaros/openfoam/runs/mesio_dev/c3d8M_256}
JOB=${JOB:-5270670}; NODES=${NODES:-cn356,cn357}; NN=${NN:-2}; NTPN=${NTPN:-128}
tag=$1; build=$2; density=$3; writer=${4:-}; compression=${5:-}

opts=""
[ -n "$writer" ] && opts="$opts
    writer          $writer;"
[ -n "$compression" ] && opts="$opts
    compression     $compression;"
cat > $CASE/system/functionsVis <<EOF
// generated by scripts/tests/bench_mesioVDB_writer.sh ($tag)
Q1
{
    type            Q;
    libs            (fieldFunctionObjects);
    field           U;
    result          Q;
    executeControl  timeStep;
    executeInterval 10;
    writeControl    none;
}

mesioVDB1
{
    type            mesioVDB;
    libs            (mesioFoam);
    writeControl    timeStep;
    writeInterval   10;
    fields          (U p Q);
    density         $density;
    outputDir       "VDB_$tag";
    filePattern     "cavity3D_%TIMEINDEX%.vdb";
    staleField      error;
    outputPolicy    vdbOnly;$opts
}
EOF

if [ "$build" = prod ]; then
    LAUNCH=$PROJ/scripts/cases/ofexec_vis.sh
else # Mesio variant: install/mesio-<build> + install/openfoam-modules-mesio-<build>/lib
    LAUNCH=$PROJ/scripts/cases/ofexec_vis_mesiodev.sh
    export MESIO_DEV_ROOT=$PROJ/install/mesio-$build
    export MESIO_DEV_FOLIB=$PROJ/install/openfoam-modules-mesio-$build/lib
    [ -f $MESIO_DEV_FOLIB/libmesioFoam.so ] || { echo "no $MESIO_DEV_FOLIB/libmesioFoam.so" >&2; exit 1; }
fi

start=$(date +%s)
UCX_TLS=${UCX_TLS:-ud,sm,self} srun --jobid=$JOB --overlap --mpi=pmix -N$NN -w $NODES --ntasks-per-node=$NTPN --cpu-bind=cores \
    bash $LAUNCH $CASE icoFoam -parallel > $CASE/log.icoFoam.$tag 2>&1
echo "== $tag ($build, density $density, writer ${writer:-default}, compression ${compression:-default}): wall $(( $(date +%s) - start )) s"
grep -E "setup time|voxels [0-9]|time \[s\]|phases|total export" $CASE/log.icoFoam.$tag
