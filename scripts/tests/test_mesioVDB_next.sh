#!/bin/bash
# mesioVDB with a Mesio build variant (default: next) on a decomposed icoFoam cavity3D case,
# with floating-point exception trapping (FOAM_SIGFPE=true unless FPE=false).
#
# Usage (login node; the work runs inside the Slurm job):
#   bash scripts/tests/test_mesioVDB_next.sh <case> <tag> <variant> <test> [writer] [compression]
#     case     decomposed case directory (runs/mesio_fix/c3d1M_128 or c3d8M_256)
#     variant  next | dev | ... (install/mesio-<variant> + install/openfoam-modules-mesio-<variant>/lib)
#     test     box      one mesioVDB, box (0 0 0) (BOX_X BOX_Y BOX_Z) with voxel size VOXEL: the
#                       voxel centres coincide with mesh points (the wind-farm FPE condition)
#                       and most ranks have no cells in the box
#              two      box (as 'box') + a second instance on the whole mesh with cell sampling
#              warn     an unwritable output directory with onError warn (run must reach End)
#              error    the same with onError error (FatalError with the Mesio message)
# Environment: JOB, NODES, NN (nodes), NTPN (ranks per node), STEPS (default 20, export every 10),
#   VOXEL, BOX_X, BOX_Y, BOX_Z (domain [0, 0.1]^3; defaults 0.00025, 0.04, 0.03, 0.1),
#   FPE (true|false), EXTRA (extra mesioVDB entries of the box instance)
# Output: <case>/VDB_<tag>/, log <case>/log.icoFoam.<tag>
set -euo pipefail
PROJ=/mnt/proj2/eu-25-121/milanjaros/openfoam
CASE=$1; tag=$2; variant=$3; test=$4; writer=${5:-}; compression=${6:-}
JOB=${JOB:-5275975}; NODES=${NODES:-cn317,cn318}; NN=${NN:-2}; NTPN=${NTPN:-128}
STEPS=${STEPS:-20}; VOXEL=${VOXEL:-0.00025}; BOX_X=${BOX_X:-0.04}; BOX_Y=${BOX_Y:-0.03}; BOX_Z=${BOX_Z:-0.1}
FPE=${FPE:-true}
EXTRA=${EXTRA:-}

opts=""
[ -n "$writer" ] && opts="$opts
    writer          $writer;"
[ -n "$compression" ] && opts="$opts
    compression     $compression;"

instance() { # name outputDir extra-entries
cat <<EOF
$1
{
    type            mesioVDB;
    libs            (mesioFoam);
    writeControl    timeStep;
    writeInterval   10;
    fields          (U p Q);
    outputDir       "$2";
    filePattern     "cavity3D_%TIMEINDEX%.vdb";
    staleField      error;
    outputPolicy    vdbOnly;$opts
$3
}
EOF
}

box="    box             (0 0 0) ($BOX_X $BOX_Y $BOX_Z);
    voxelSize       $VOXEL;$EXTRA"
{
cat <<EOF
// generated by scripts/tests/test_mesioVDB_next.sh ($tag, $variant, $test)
Q1
{
    type            Q;
    libs            (fieldFunctionObjects);
    field           U;
    result          Q;
    executeControl  timeStep;
    executeInterval 10;
    writeControl    none;
}
EOF
case $test in
box)   instance mesioVDB1 "VDB_$tag" "$box" ;;
two)   instance mesioVDB1 "VDB_$tag" "$box"
       instance mesioVDB2 "VDB_${tag}_cell" "    density         100;
    sampling        cell;
    memoryTracking  true;" ;;
warn)  instance mesioVDB1 "/proc/mesio_no_such_dir" "$box
    onError         warn;"
       instance mesioVDB2 "VDB_${tag}" "    density         50;" ;;
error) instance mesioVDB1 "/proc/mesio_no_such_dir" "$box
    onError         error;" ;;
*) echo "unknown test $test" >&2; exit 1 ;;
esac
} > $CASE/system/functionsVis

sed -i "s/^endTime .*/endTime         $(python3 -c "print(round($STEPS*0.001, 6))");/" $CASE/system/controlDict
grep -q '#include "functionsVis"' $CASE/system/controlDict || { echo "controlDict of $CASE does not include functionsVis" >&2; exit 1; }

case $variant in
prod) LAUNCH=$PROJ/scripts/cases/ofexec_vis.sh ;;
next) LAUNCH=$PROJ/scripts/cases/ofexec_vis_mesionext.sh ;;
*)    LAUNCH=$PROJ/scripts/cases/ofexec_vis_mesiodev.sh
      export MESIO_DEV_ROOT=$PROJ/install/mesio-$variant
      export MESIO_DEV_FOLIB=$PROJ/install/openfoam-modules-mesio-$variant/lib ;;
esac

rm -rf $CASE/VDB_$tag $CASE/VDB_${tag}_cell
start=$(date +%s)
FOAM_SIGFPE=$FPE UCX_TLS=${UCX_TLS:-ud,sm,self} srun --jobid=$JOB --overlap --mpi=pmix -N$NN -w $NODES --ntasks-per-node=$NTPN --cpu-bind=cores \
    bash $LAUNCH $CASE icoFoam -parallel > $CASE/log.icoFoam.$tag 2>&1 && rc=0 || rc=$?
echo "== $tag ($variant, $test, writer ${writer:-default}, compression ${compression:-default}, FOAM_SIGFPE=$FPE): rc $rc, wall $(( $(date +%s) - start )) s"
grep -E "trapFpe|sigFpe|Floating point|setup time|voxels  *:|voxels [0-9]|time \[s\]|memory \[MB\]|Mesio error|skipped|rebuilt|FOAM FATAL|^End" $CASE/log.icoFoam.$tag | sort | uniq -c | sort -rn | head -20
exit $rc
